/** Refresh the two example outputs from menu.css; not a plugin/Tailwind build. */
import { readFileSync, writeFileSync } from 'node:fs';

const read = name => readFileSync(new URL(name, import.meta.url), 'utf8');
const write = (name, text) => writeFileSync(new URL(name, import.meta.url), text, 'utf8');
const runtime = read('../../../wp-content/themes/skvn-marine/assets/js/animations.js');
const controller = runtime.split('/* MARINE_MENU_DRAWER_START */')[1]?.split('/* MARINE_MENU_DRAWER_END */')[0]?.trim();
if (!controller) throw new Error('Missing menu controller in shared theme runtime');
write('mobile-drawer.js', controller + '\n');
const css = read('menu.css');
const marker = '/* Standalone utility fallbacks. WindPress supplies these in its own path. */';
if (css.split(marker).length !== 2) throw new Error('Expected one standalone utility boundary');

const utilities = 'bg-white grid grid-cols-1 gap-8 md:grid-cols-3 min-w-0 flex flex-wrap items-center justify-between gap-x-8 gap-y-4 gap-x-6 gap-y-3 mx-auto w-full px-5 py-5';
write('windpress.css', `/* Generated by sync-preview.mjs from menu.css.
 * Replace the old menu CSS in the existing WindPress stylesheet.
 * Keep these rules OUTSIDE @layer: GP/core normal rules are unlayered.
 * Do not wrap this snippet in a named layer or import Tailwind again. */
@source inline("${utilities}");
${css.split(marker)[0].trim()}\n`);

// Only the standalone viewer replaces the dynamic Site Title and opens Products.
// Gutenberg source and its saved block attributes remain unchanged.
let header = read('header.gutenberg.html')
  .replace(/<!-- wp:site-title[\s\S]*?\/-->/, '<p class="marine-menu-brand wp-block-site-title"><a href="#">Your site name</a></p>')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace('<details class="wp-block-details marine-menu-disclosure">', '<details open class="wp-block-details marine-menu-disclosure">');

write('preview.html', `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Gutenberg mega-menu prototype</title>
<link rel="stylesheet" href="./menu.css">
<style>
/* Deliberately AFTER menu.css: reproduce the observed GP/core cascade conflict.
 * This small fixture is not a copy of the complete WordPress/theme runtime. */
*,*::before,*::after{box-sizing:border-box}
body{margin:0;font-family:system-ui,sans-serif;font-size:17px;line-height:1.5;background:#f8fafc}
p{margin:0 0 1.5em}
a{color:#1e73be;text-decoration:underline}
h3{font-size:29px;line-height:1.2;font-weight:400;margin:0 0 20px;text-transform:none}
body:not(.wp-admin) .wp-block-heading{font-family:Georgia,serif;letter-spacing:0;color:#082f49}
.wp-block-button .wp-block-button__link{display:inline-block;padding:10px 20px;font-size:inherit;line-height:inherit}
a.wp-block-button__link:not(.has-background){color:#fff;background-color:#55555e}
.preview-notes{max-width:1200px;margin:32px auto;padding:24px;min-height:110vh;color:#526570;line-height:1.6}
.preview-notes p{margin:0 0 12px}
</style>
<script src="./mobile-drawer.js" defer></script></head><body>
<header>${header}</header>
<main class="preview-notes"><p>Desktop: click Products. Mobile: open Menu to see the sliding drawer.</p><p>All menu URLs are placeholders. Resize below 768px; try Close, Escape, and the backdrop.</p><p>This viewer uses menu.css directly, with theme-like conflicting styles loaded after it. WordPress/WindPress integration still needs testing.</p></main>
</body></html>
`);
console.log('Updated example CSS/viewer and controller mirror; no plugin/Tailwind build.');
